#!/usr/bin/env node
// scripts/build-embed-docs.mjs
// Converts docs/EMBEDDING.md into a committed HTML fragment
// (js/gen/embedding-docs.html) that the Embed Builder page fetches into its
// help dialog. Mirrors scripts/build-embed.mjs's generator + byte-compare +
// failure messaging conventions; `npm run check` (--check) fails CI on drift.
// Usage: node scripts/build-embed-docs.mjs [--check]: --check verifies
// only, writes nothing.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Marked } from "marked";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, "..");

const CHECK_MODE = process.argv.includes("--check");

const SRC_PATH = path.join(REPO_ROOT, "docs", "EMBEDDING.md");
const OUT_PATH = path.join(REPO_ROOT, "js", "gen", "embedding-docs.html");
const OUT_REL = "js/gen/embedding-docs.html";

// Canonicalize to LF: a Windows checkout's autocrlf setting would otherwise
// leak CRLF into the emitted output and break the --check byte-compare
// against a Linux-generated commit (same hazard build-embed.mjs guards).
const normalizeEol = (s) => s.replace(/\r\n/g, "\n");

function log(...args) {
  console.log("[build-embed-docs]", ...args);
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

function escapeAttr(s) {
  return String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;");
}

// Approximates GitHub's heading slugger closely enough for this document's
// own internal anchors (#events, #theming, etc.) to resolve: lowercase,
// drop punctuation other than spaces/hyphens/word chars, collapse
// whitespace runs to a single hyphen.
function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^\w\- ]+/g, "")
    .trim()
    .replace(/ +/g, "-");
}

/** Builds a marked Renderer override that assigns slug ids to h2/h3
 * headings only (matching the doc's own anchor targets), disambiguating
 * repeats, and reports every id it minted via onId. */
function makeRenderer(marked, onId) {
  const usedSlugs = new Map();

  function uniqueSlug(base) {
    const count = usedSlugs.get(base) || 0;
    usedSlugs.set(base, count + 1);
    return count === 0 ? base : `${base}-${count}`;
  }

  return {
    heading(token) {
      const html = this.parser.parseInline(token.tokens);
      if (token.depth !== 2 && token.depth !== 3) {
        return `<h${token.depth}>${html}</h${token.depth}>\n`;
      }
      const id = uniqueSlug(slugify(token.text));
      onId(id);
      return `<h${token.depth} id="${id}">${html}</h${token.depth}>\n`;
    },
    link(token) {
      const text = this.parser.parseInline(token.tokens);
      const href = token.href;
      let out = `<a href="${escapeAttr(href)}"`;
      if (/^https?:\/\//i.test(href)) {
        out += ` target="_blank" rel="noopener"`;
      }
      if (token.title) {
        out += ` title="${escapeAttr(token.title)}"`;
      }
      out += `>${text}</a>`;
      return out;
    },
  };
}

/** Collects every `(#anchor)` reference in the raw markdown source, so
 * dangling internal links can be caught even if a future renderer change
 * stops passing them through unchanged. */
function collectInternalAnchors(markdown) {
  const anchors = new Set();
  const re = /\]\(#([\w-]+)\)/g;
  let m;
  while ((m = re.exec(markdown)) !== null) {
    anchors.add(m[1]);
  }
  return anchors;
}

/** Renders docs/EMBEDDING.md to the final HTML fragment in memory. Never
 * writes anything: the caller decides whether to write (normal mode) or
 * byte-compare against the committed file (--check mode). */
async function render() {
  const source = normalizeEol(await readFile(SRC_PATH, "utf8"));

  const headingIds = new Set();
  const marked = new Marked({ gfm: true });
  marked.use({ renderer: makeRenderer(marked, (id) => headingIds.add(id)) });

  const body = marked.parse(source, { async: false });

  const internalAnchors = collectInternalAnchors(source);
  const dangling = [...internalAnchors].filter((a) => !headingIds.has(a));
  if (dangling.length > 0) {
    fail(
      "error: docs/EMBEDDING.md has internal anchor link(s) with no matching heading id:\n" +
        dangling.map((a) => `  - #${a}`).join("\n") +
        "\nCheck the heading text/slug in docs/EMBEDDING.md, or scripts/build-embed-docs.mjs's slugify() if the heading text looks right."
    );
  }

  const comment = `<!-- Generated by scripts/build-embed-docs.mjs from docs/EMBEDDING.md. Do not edit directly. -->\n`;
  const html = normalizeEol(`${comment}<div class="embed-help-doc">\n${body}</div>\n`);

  if (Buffer.byteLength(html) < 5 * 1024) {
    fail("error: rendered embedding-docs.html is suspiciously small (< 5KB): a silent empty/partial render must not pass.");
  }
  if (!html.includes("<table")) {
    fail('error: rendered embedding-docs.html has no "<table": docs/EMBEDDING.md is table-heavy, so a render missing every table indicates a broken conversion.');
  }

  return html;
}

async function main() {
  const html = await render();

  if (CHECK_MODE) {
    if (!existsSync(OUT_PATH)) {
      fail(`${OUT_REL} is stale - run \`npm run build:embeddocs\` (or \`npm run build\`) and commit`);
    }
    const committed = normalizeEol(await readFile(OUT_PATH, "utf8"));
    if (committed !== html) {
      let firstDiffLine = null;
      const committedLines = committed.split("\n");
      const htmlLines = html.split("\n");
      for (let i = 0; i < Math.max(committedLines.length, htmlLines.length); i++) {
        if (committedLines[i] !== htmlLines[i]) {
          firstDiffLine = i + 1;
          break;
        }
      }
      fail(
        `${OUT_REL} is stale - run \`npm run build:embeddocs\` (or \`npm run build\`) and commit` +
          (firstDiffLine ? ` (first differing line: ${firstDiffLine})` : "")
      );
    }
    log(`OK: ${OUT_REL} matches a fresh build.`);
    return;
  }

  await mkdir(path.dirname(OUT_PATH), { recursive: true });
  await writeFile(OUT_PATH, html);
  log(`wrote ${OUT_REL}: ${Buffer.byteLength(html)} bytes`);
}

await main();
