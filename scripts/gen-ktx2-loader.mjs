#!/usr/bin/env node
// scripts/gen-ktx2-loader.mjs
//
// One-off generator (not part of the vendor.mjs COPIES table, because it
// transforms rather than verbatim-copies): inlines three@0.128.0's ES-module
// KTX2Loader stack (jsm/loaders/KTX2Loader.js, jsm/loaders/BasisTextureLoader.js,
// jsm/libs/ktx-parse.module.js, jsm/libs/zstddec.module.js) into a single plain
// <script>-loadable vendor/three/KTX2Loader.js, matching the non-module UMD-ish
// style of the r128 examples/js loaders (DRACOLoader.js etc). The r128
// examples/js tree ships no KTX2Loader at all, only the jsm (ES module) one,
// which our shell.jsx / embed.html <script> tags cannot import directly.
//
// Run once: node scripts/gen-ktx2-loader.mjs
// Re-run whenever the pinned "three" devDependency version changes.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const JSM = path.join(REPO_ROOT, "node_modules/three/examples/jsm");
const OUT = path.join(REPO_ROOT, "vendor/three/KTX2Loader.js");

function stripImports(src) {
  // Drop every `import ... from '...';` statement (single or multi-line).
  return src.replace(/^import\s*\{[\s\S]*?\}\s*from\s*['"][^'"]+['"];\s*$/gm, "").replace(/^import\s+\{[^}]*\}\s+from\s+['"][^'"]+['"];\s*$/gm, "");
}

function stripExportKeyword(src) {
  return src.replace(/^export\s+class\b/gm, "class").replace(/^export\s+default\s+/gm, "");
}

function extractTrailingExportBraces(src) {
  // Matches a trailing `export { a, b as c, ... };` (with or without newlines
  // before it) or a minified `export{...};` and returns [body, names[]]
  const m = src.match(/export\s*\{([^}]*)\}\s*;?\s*$/);
  if (!m) return [src, []];
  const body = src.slice(0, m.index);
  const names = m[1]
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((entry) => {
      const asMatch = entry.match(/^(\S+)\s+as\s+(\S+)$/);
      return asMatch ? { local: asMatch[1], exported: asMatch[2] } : { local: entry, exported: entry };
    });
  return [body, names];
}

async function main() {
  const ktxParseRaw = await readFile(path.join(JSM, "libs/ktx-parse.module.js"), "utf8");
  const zstdRaw = await readFile(path.join(JSM, "libs/zstddec.module.js"), "utf8");
  const basisRaw = await readFile(path.join(JSM, "loaders/BasisTextureLoader.js"), "utf8");
  const ktx2Raw = await readFile(path.join(JSM, "loaders/KTX2Loader.js"), "utf8");

  const [ktxParseBody, ktxParseExports] = extractTrailingExportBraces(ktxParseRaw);
  const ktxParseReturn = `return { ${ktxParseExports.map((e) => (e.local === e.exported ? e.local : `${e.exported}: ${e.local}`)).join(", ")} };`;

  const zstdBody = stripExportKeyword(zstdRaw);

  const basisBody = stripImports(basisRaw).replace(/^export\s*\{\s*BasisTextureLoader\s*\}\s*;?\s*$/m, "");
  const basisImportNames = [
    "CompressedTexture",
    "FileLoader",
    "LinearFilter",
    "LinearMipmapLinearFilter",
    "Loader",
    "RGBAFormat",
    "RGBA_ASTC_4x4_Format",
    "RGBA_BPTC_Format",
    "RGBA_ETC2_EAC_Format",
    "RGBA_PVRTC_4BPPV1_Format",
    "RGBA_S3TC_DXT5_Format",
    "RGB_ETC1_Format",
    "RGB_ETC2_Format",
    "RGB_PVRTC_4BPPV1_Format",
    "RGB_S3TC_DXT1_Format",
    "UnsignedByteType",
  ];

  let ktx2Body = ktx2Raw;
  ktx2Body = ktx2Body.replace(/^import\s*\{[\s\S]*?\}\s*from\s*['"]three['"];\s*$/m, "const { CompressedTexture, CompressedTextureLoader, FileLoader, LinearEncoding, sRGBEncoding } = THREE;");
  ktx2Body = ktx2Body.replace(/^import\s*\{[\s\S]*?\}\s*from\s*['"]\.\.\/libs\/ktx-parse\.module\.js['"];\s*$/m, "const { read: readKTX, KTX2ChannelETC1S, KTX2ChannelUASTC, KTX2Flags, KTX2Model, KTX2SupercompressionScheme, KTX2Transfer } = KtxParseModule;");
  ktx2Body = ktx2Body.replace(/^import\s*\{\s*BasisTextureLoader\s*\}\s*from\s*['"]\.\/BasisTextureLoader\.js['"];\s*$/m, "const { BasisTextureLoader } = BasisTextureLoaderModule;");
  ktx2Body = ktx2Body.replace(/^import\s*\{\s*ZSTDDecoder\s*\}\s*from\s*['"]\.\.\/libs\/zstddec\.module\.js['"];\s*$/m, "const { ZSTDDecoder } = ZstdModule;");
  ktx2Body = ktx2Body.replace(/^export\s*\{\s*KTX2Loader\s*\}\s*;?\s*$/m, "");

  const out = `// vendor/three/KTX2Loader.js
// Generated by scripts/gen-ktx2-loader.mjs from three@0.128.0's ES-module
// jsm/loaders/KTX2Loader.js + jsm/loaders/BasisTextureLoader.js +
// jsm/libs/ktx-parse.module.js + jsm/libs/zstddec.module.js, inlined and
// stripped of import/export syntax for plain <script> loading (three's
// r128 examples/js tree ships no KTX2Loader). Do not hand-edit; re-run the
// generator instead. License: three.js MIT (vendor/three/LICENSE.txt).
(function () {

var KtxParseModule = (function () {
${ktxParseBody}
${ktxParseReturn}
})();

var ZstdModule = (function () {
const exportsObj = {};
${zstdBody}
exportsObj.ZSTDDecoder = ZSTDDecoder;
return exportsObj;
})();

var BasisTextureLoaderModule = (function () {
const { ${basisImportNames.join(", ")} } = THREE;
${basisBody}
return { BasisTextureLoader };
})();

var KTX2LoaderModule = (function () {
${ktx2Body}
return { KTX2Loader };
})();

THREE.KTX2Loader = KTX2LoaderModule.KTX2Loader;
THREE.BasisTextureLoader = BasisTextureLoaderModule.BasisTextureLoader;

})();
`;

  await writeFile(OUT, out);
  console.log(`wrote ${path.relative(REPO_ROOT, OUT)} (${out.length} bytes)`);
}

main();
